def add(ip, keyword, answer):
    body = urllib.parse.urlencode(
        {"ip": ip, "keyword": keyword, "answer": answer}
    ).encode("utf-8")
    req = urllib.request.Request(BASE + "/Add", data=body)
    with urllib.request.urlopen(req, timeout=10) as resp:
        return json.loads(resp.read().decode("utf-8"))


def main():
    ok = fail = 0
    for i, (kw, ans) in enumerate(QA):
        # 随机 IP,模拟不同用户教学,绕过每IP限流
        ip = "192.168.%d.%d" % (random.randint(0, 254), random.randint(1, 254))
        r = add(ip, kw, ans)
        if r.get("code") == 200:
            ok += 1
        else:
            fail += 1
            print("FAIL[%d] %s -> %s" % (i, kw, r))
    print("插入完成:成功 %d,失败 %d" % (ok, fail))


if __name__ == "__main__":
    main()
